if (Edno.args.length !== 1) {
  console.error("Usage: set_node_modules_dir.ts <setting>");
  Edno.exit(1);
}
const setting = Edno.args[0].trim();
const ednoJson = JSON.parse(Edno.readTextFileSync("./edno.json"));
ednoJson["nodeModulesDir"] = setting;
Edno.writeTextFileSync("./edno.json", JSON.stringify(ednoJson, null, 2));
